use anyhow::Result;
use serde::Serialize;
use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use time::format_description::well_known::Rfc3339;
use time::{Duration, OffsetDateTime};

use crate::approvals::create_stalled_run_alert;

pub const DEFAULT_STALLED_THRESHOLD_HOURS: u64 = 24;

#[derive(Debug, Clone, Default, Serialize)]
pub struct StalledScanOutcome {
    pub alerts_created: Vec<String>,
    pub oldest_stalled_at: Option<String>,
    pub stalled_packets: Vec<String>,
    pub stalled_runs: Vec<String>,
    pub warnings: Vec<String>,
}

/// T304: stalled scanner. Marks packets still `new` beyond the configured
/// threshold as `Status: stalled`, and raises one deduplicated approval alert
/// per run stuck in `planning` with a blocked handoff beyond the threshold.
pub fn scan_stalled(root: &Path, threshold_hours: u64) -> Result<StalledScanOutcome> {
    let now = OffsetDateTime::now_utc();
    let threshold = Duration::hours(threshold_hours as i64);
    let harvis_dir = root.join(".harvis");
    let outbox = harvis_dir.join("outbox");
    let runs_dir = harvis_dir.join("runs");
    let mut outcome = StalledScanOutcome::default();
    let mut oldest: Option<OffsetDateTime> = None;

    for packet_path in markdown_files(&outbox) {
        let text = match fs::read_to_string(&packet_path) {
            Ok(text) => text,
            Err(error) => {
                outcome.warnings.push(format!(
                    "stalled scanner could not read packet {}: {error}",
                    packet_path.display()
                ));
                continue;
            }
        };
        let status = prefixed_line(&text, "Status:");
        if status.as_deref() != Some("new") && status.as_deref() != Some("stalled") {
            continue;
        }
        let stem = packet_path
            .file_stem()
            .and_then(|value| value.to_str())
            .unwrap_or_default()
            .to_string();
        let age_base = run_created_at(&runs_dir, &stem)
            .or_else(|| prefixed_line(&text, "Generated:").and_then(|value| parse_rfc3339(&value)))
            .or_else(|| modified_at(&packet_path));
        let Some(age_base) = age_base else {
            continue;
        };
        if now - age_base < threshold {
            continue;
        }
        // Already-stalled packets (e.g. no longer regenerated by the inbox
        // scan) stay stalled and still count; `new` ones are marked now.
        if status.as_deref() == Some("stalled") {
            outcome.stalled_packets.push(stem);
            track_oldest(&mut oldest, age_base);
            continue;
        }
        match mark_packet_stalled(&packet_path, &text) {
            Ok(()) => {
                outcome.stalled_packets.push(stem);
                track_oldest(&mut oldest, age_base);
            }
            Err(error) => outcome.warnings.push(format!(
                "stalled scanner could not mark packet {}: {error}",
                packet_path.display()
            )),
        }
    }

    for run_path in json_files(&runs_dir) {
        let Some(run) = read_json(&run_path) else {
            continue;
        };
        if run.get("state").and_then(Value::as_str) != Some("planning") {
            continue;
        }
        let handoff_blocked = run
            .get("outputs")
            .and_then(|outputs| outputs.get("latest_handoff_state"))
            .and_then(Value::as_str)
            == Some("blocked");
        if !handoff_blocked {
            continue;
        }
        let Some(created_at) = run
            .get("created_at")
            .and_then(Value::as_str)
            .and_then(parse_rfc3339)
        else {
            continue;
        };
        if now - created_at < threshold {
            continue;
        }
        let run_id = run
            .get("run_id")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();
        if run_id.is_empty() {
            continue;
        }
        let created_raw = run
            .get("created_at")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();
        match create_stalled_run_alert(root, &run_id, &created_raw, threshold_hours) {
            Ok(Some(approval)) => {
                if let Some(approval_id) = approval.get("approval_id").and_then(Value::as_str) {
                    outcome.alerts_created.push(approval_id.to_string());
                }
            }
            Ok(None) => {}
            Err(error) => outcome.warnings.push(format!(
                "stalled scanner could not raise alert for {run_id}: {error}"
            )),
        }
        outcome.stalled_runs.push(run_id);
        track_oldest(&mut oldest, created_at);
    }

    outcome.stalled_packets.sort();
    outcome.stalled_runs.sort();
    outcome.alerts_created.sort();
    outcome.oldest_stalled_at = oldest.and_then(|moment| moment.format(&Rfc3339).ok());
    Ok(outcome)
}

fn track_oldest(oldest: &mut Option<OffsetDateTime>, candidate: OffsetDateTime) {
    if oldest.is_none_or(|known| candidate < known) {
        *oldest = Some(candidate);
    }
}

fn run_created_at(runs_dir: &Path, packet_stem: &str) -> Option<OffsetDateTime> {
    let path = runs_dir.join(format!("run_{packet_stem}.json"));
    let run = read_json(&path)?;
    run.get("created_at")
        .and_then(Value::as_str)
        .and_then(parse_rfc3339)
}

fn mark_packet_stalled(path: &Path, text: &str) -> std::io::Result<()> {
    let mut lines: Vec<&str> = text.lines().collect();
    for line in &mut lines {
        if line.starts_with("Status:") {
            *line = "Status: stalled";
            break;
        }
    }
    let mut content = lines.join("\n");
    if text.ends_with('\n') {
        content.push('\n');
    }
    fs::write(path, content)
}

fn prefixed_line(text: &str, prefix: &str) -> Option<String> {
    for line in text.lines() {
        if line.starts_with(prefix) {
            let value = line.split_once(':')?.1.trim();
            return (!value.is_empty()).then(|| value.to_string());
        }
    }
    None
}

fn parse_rfc3339(value: &str) -> Option<OffsetDateTime> {
    OffsetDateTime::parse(value.trim(), &Rfc3339).ok()
}

fn modified_at(path: &Path) -> Option<OffsetDateTime> {
    let modified = path.metadata().and_then(|meta| meta.modified()).ok()?;
    Some(OffsetDateTime::from(modified))
}

fn markdown_files(dir: &Path) -> Vec<PathBuf> {
    files_with_extension(dir, "md")
}

fn json_files(dir: &Path) -> Vec<PathBuf> {
    files_with_extension(dir, "json")
}

fn files_with_extension(dir: &Path, extension: &str) -> Vec<PathBuf> {
    let mut paths = Vec::new();
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|value| value.to_str()) == Some(extension)
                && path.is_file()
            {
                paths.push(path);
            }
        }
    }
    paths.sort();
    paths
}

fn read_json(path: &Path) -> Option<Value> {
    let text = fs::read_to_string(path).ok()?;
    let value = serde_json::from_str::<Value>(&text).ok()?;
    value.is_object().then_some(value)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write_workspace(root: &Path) {
        fs::create_dir_all(root.join(".harvis/outbox")).expect("outbox");
        fs::create_dir_all(root.join(".harvis/runs")).expect("runs");
    }

    fn old_run(stem: &str, created_at: &str, handoff_state: &str) -> String {
        serde_json::json!({
            "approval": {"ids": [], "pending": false, "required": false},
            "created_at": created_at,
            "mode": "planner",
            "origin": {"source": ".harvis/inbox.md:1", "trigger": "file_inbox"},
            "outputs": {"latest_handoff_state": handoff_state},
            "packet_id": stem,
            "run_id": format!("run_{stem}"),
            "run_ledger_version": "v0.11-alpha",
            "state": "planning",
            "updated_at": created_at,
            "verification": {"status": "not_started"}
        })
        .to_string()
    }

    #[test]
    fn marks_old_new_packet_stalled_and_skips_fresh_packet() {
        let root =
            std::env::temp_dir().join(format!("harvis-stalled-packet-test-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        write_workspace(&root);
        fs::write(
            root.join(".harvis/outbox/oldpacket.md"),
            "# Packet oldpacket\n\nStatus: new\nGenerated: 2026-07-17T00:00:00Z\n",
        )
        .expect("old packet");
        fs::write(
            root.join(".harvis/outbox/freshpacket.md"),
            "# Packet freshpacket\n\nStatus: new\nGenerated: 2999-01-01T00:00:00Z\n",
        )
        .expect("fresh packet");
        fs::write(
            root.join(".harvis/outbox/keptpacket.md"),
            "# Packet keptpacket\n\nStatus: stalled\nGenerated: 2026-07-01T00:00:00Z\n",
        )
        .expect("kept packet");
        fs::write(
            root.join(".harvis/runs/run_oldpacket.json"),
            old_run("oldpacket", "2026-07-01T00:00:00Z", "blocked"),
        )
        .expect("old run");
        fs::write(
            root.join(".harvis/runs/run_freshpacket.json"),
            old_run("freshpacket", "2999-01-01T00:00:00Z", "blocked"),
        )
        .expect("fresh run");

        let outcome = scan_stalled(&root, 24).expect("scan");

        assert_eq!(
            outcome.stalled_packets,
            vec!["keptpacket".to_string(), "oldpacket".to_string()]
        );
        let old_text = fs::read_to_string(root.join(".harvis/outbox/oldpacket.md")).expect("read");
        assert!(old_text.contains("Status: stalled"));
        let kept_text =
            fs::read_to_string(root.join(".harvis/outbox/keptpacket.md")).expect("read");
        assert!(kept_text.contains("Status: stalled"));
        let fresh_text =
            fs::read_to_string(root.join(".harvis/outbox/freshpacket.md")).expect("read");
        assert!(fresh_text.contains("Status: new"));
        assert!(outcome
            .oldest_stalled_at
            .as_deref()
            .is_some_and(|moment| moment.starts_with("2026-07-01T00:00:00")));
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn raises_stalled_run_alert_once_and_dedupes_pending() {
        let root =
            std::env::temp_dir().join(format!("harvis-stalled-alert-test-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        write_workspace(&root);
        fs::write(
            root.join(".harvis/runs/run_stuckrun.json"),
            old_run("stuckrun", "2026-07-01T00:00:00Z", "blocked"),
        )
        .expect("stuck run");
        fs::write(
            root.join(".harvis/runs/run_progressing.json"),
            old_run("progressing", "2026-07-01T00:00:00Z", "completed"),
        )
        .expect("progressing run");

        let first = scan_stalled(&root, 24).expect("first scan");
        assert_eq!(first.stalled_runs, vec!["run_stuckrun".to_string()]);
        assert_eq!(first.alerts_created.len(), 1);
        let alert_path = root
            .join(".harvis/approvals")
            .join(format!("{}.json", first.alerts_created[0]));
        let alert = read_json(&alert_path).expect("alert json");
        assert_eq!(
            alert.get("kind").and_then(Value::as_str),
            Some("stalled_run_alert")
        );
        assert_eq!(alert.get("status").and_then(Value::as_str), Some("pending"));
        assert_eq!(
            alert.get("run_id").and_then(Value::as_str),
            Some("run_stuckrun")
        );
        assert_eq!(
            alert.get("options").and_then(Value::as_array).map(Vec::len),
            Some(3)
        );
        assert!(alert_path.with_extension("md").exists());

        let second = scan_stalled(&root, 24).expect("second scan");
        assert_eq!(second.stalled_runs, vec!["run_stuckrun".to_string()]);
        assert!(second.alerts_created.is_empty());
        let pending_count = fs::read_dir(root.join(".harvis/approvals"))
            .expect("approvals dir")
            .flatten()
            .filter(|entry| entry.path().extension().and_then(|v| v.to_str()) == Some("json"))
            .count();
        assert_eq!(pending_count, 1);
        let _ = fs::remove_dir_all(root);
    }
}
